// Handles requests to routes that don't exist
export const notFound = (req, res, next) => {
  const error = new Error(`Not Found - ${req.originalUrl}`);
  res.status(404);
  next(error);
};

// Centralized error handler - catches errors thrown/passed via next(error)
export const errorHandler = (err, req, res, next) => {
  let statusCode = res.statusCode === 200 ? 500 : res.statusCode;
  let message = err.message;

  // Mongoose bad ObjectId
  if (err.name === "CastError" && err.kind === "ObjectId") {
    statusCode = 404;
    message = "Resource not found";
  }

  // Mongoose duplicate key
  if (err.code === 11000) {
    statusCode = 400;
    const field = Object.keys(err.keyValue)[0];
    message = `${field} already exists`;
  }

  // Mongoose validation error
  if (err.name === "ValidationError") {
    statusCode = 400;
    message = Object.values(err.errors)
      .map((val) => val.message)
      .join(", ");
  }

  // Multer upload errors (file too large, too many files, etc.)
  if (err.name === "MulterError") {
    statusCode = 400;
    const messages = {
      LIMIT_FILE_SIZE: "One of your files is larger than the 5MB limit.",
      LIMIT_FILE_COUNT: "You can attach at most 3 files to a project.",
      LIMIT_UNEXPECTED_FILE: "Unexpected file field in upload.",
    };
    message = messages[err.code] || `File upload error: ${err.message}`;
  }

  res.status(statusCode).json({
    success: false,
    message,
    stack: process.env.NODE_ENV === "production" ? null : err.stack,
  });
};
